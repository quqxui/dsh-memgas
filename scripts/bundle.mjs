// Builds the single-file plugin artifact that ships in this repository.
//
// The bundle exists so `dsh plugin add github:...` works: a git install
// delivers source, never build output, and it will not run a build script
// without the user granting pnpm's build permission. Committing one
// dependency-free file removes both problems.
import { build } from 'esbuild'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

await build({
  entryPoints: [join(root, 'packages/dsh-plugin/src/index.ts')],
  outfile: join(root, 'dist/index.js'),
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node22.19',
  // Bundled from source, so the artifact never depends on the build order of
  // the workspace packages.
  alias: { 'memgas-core': join(root, 'packages/core/src/index.ts') },
  // Loaded through a runtime dynamic import only when the user opts into a
  // local embedding model; it must stay out of the bundle.
  external: ['@huggingface/transformers'],
  banner: {
    js: '// dsh-memgas — generated by scripts/bundle.mjs, do not edit.\n' +
      '// Source: https://github.com/quqxui/dsh-memgas',
  },
  legalComments: 'none',
  logLevel: 'info',
})
